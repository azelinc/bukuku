import json
import random

random.seed(42)

def shuffle_q(q):
    opts = q["a"]
    correct = opts[q["c"]]
    random.shuffle(opts)
    q["a"] = opts
    q["c"] = opts.index(correct)
    return q

def q(q_text, opts, correct_idx):
    """Helper: creates one question dict and immediately shuffles."""
    d = {"q": q_text, "a": opts, "c": correct_idx}
    return shuffle_q(d)

